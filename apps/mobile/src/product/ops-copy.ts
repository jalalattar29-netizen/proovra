const DICT: Readonly<Record<OpsCopyLocale, OpsCopy>> = { en: EN, de: DE, ar: AR };

export function opsCopyFor(locale: string | null | undefined): OpsCopy {
  return locale === "de" || locale === "ar" ? DICT[locale] : EN;
}
/** The earlier name; same dictionary. */
export const opsNativeCopyFor = opsCopyFor;

/** The English dictionary, for the pure helpers' defaults. */
export const OPS_COPY_EN: OpsCopy = EN;

/** Fill `{name}` placeholders. */
export function fillOpsCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

function localeTag(locale: string | null | undefined): string {
  return locale === "de" ? "de-DE" : locale === "ar" ? "ar-u-nu-latn" : "en-US";
}

/** Locale-aware integer formatting (Arabic keeps Western digits, as the web does). */
export function formatOpsCount(n: number, locale: string | null | undefined): string {
  try {
    return n.toLocaleString(localeTag(locale));
  } catch {
    return String(n);
  }
}

/**
 * An instant in the viewer's time zone, through the product's ONE timestamp
 * authority (the repository's timestamp policy forbids formatting dates
 * anywhere else), exactly as the web does. Relative ages and every word around
 * a date are localized; the date itself is the canonical format.
 */
export function formatOpsDateTime(iso: string | null | undefined, locale: string | null | undefined): string {
  if (!iso) return opsCopyFor(locale).notAvailable;
  if (!Number.isFinite(Date.parse(iso))) return opsCopyFor(locale).notAvailable;
  return formatUserDateTime(iso);
}

/** Relative age ("3h ago"), in the dictionary's words; a month or more falls back to the date. */
export function opsRelativeTime(iso: string | null | undefined, t: OpsCopy, locale: string | null | undefined, now: number = Date.now()): string {
  if (!iso) return "—";
  const at = Date.parse(iso);
  if (!Number.isFinite(at)) return "—";
  const past = at <= now;
  const minutes = Math.floor(Math.abs(now - at) / 60_000);
  if (minutes < 1) return past ? t.justNow : t.inUnderMinute;
  if (minutes < 60) return fillOpsCopy(past ? t.minutesAgo : t.inMinutes, { n: minutes });
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return fillOpsCopy(past ? t.hoursAgo : t.inHours, { n: hours });
  const days = Math.floor(hours / 24);
  if (days < 30) return fillOpsCopy(past ? t.daysAgo : t.inDays, { n: days });
  return formatOpsDateTime(iso, locale);
}

/** A span of seconds ("2h 5m"), in the dictionary's words. */
export function opsDuration(seconds: number | null | undefined, t: OpsCopy): string {
  if (seconds == null || !Number.isFinite(seconds) || seconds < 0) return "—";
  const total = Math.floor(seconds);
  if (total < 60) return t.underMinute;
  const minutes = Math.floor(total / 60);
  if (minutes < 60) return fillOpsCopy(t.durMinutes, { n: minutes });
  const hours = Math.floor(minutes / 60);
  const restMinutes = minutes % 60;
  if (hours < 24) return restMinutes === 0 ? fillOpsCopy(t.durHours, { n: hours }) : fillOpsCopy(t.durHoursMinutes, { h: hours, m: restMinutes });
  const days = Math.floor(hours / 24);
  const restHours = hours % 24;
  return restHours === 0 ? fillOpsCopy(t.durDays, { n: days }) : fillOpsCopy(t.durDaysHours, { d: days, h: restHours });
}

