/** The Operations copy for a locale; English for any locale not written out. */
export function operationsCopyFor(locale: string | null | undefined): OperationsCopy {
  return locale === "de" || locale === "ar" ? operationsDict[locale] : operationsDict.en;
}

/** Fill `{name}` placeholders. Numbers are formatted by the caller. */
export function fillOperationsCopy(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_m, k: string) => (k in values ? String(values[k]) : `{${k}}`));
}

