/**
 * Answer from the bundle when the bundle can answer; otherwise return null and
 * let the caller take the provider path.
 *
 * Pricing is checked first for the reason given above. Topics are then tried
 * in declaration order and the FIRST match wins, so the table is ordered with
 * the specific before the general — "verification package" before a bare
 * "verify", TSA before a generic status question.
 */
export function answerProductKnowledge(
  messages: { role: string; content: string }[],
): AiResult | null {
  const lastUserMessage =
    [...messages].reverse().find((m) => m.role === "user")?.content ?? "";
  if (lastUserMessage.trim().length === 0) return null;

  if (isPricingQuestion(lastUserMessage)) return PRICING_ANSWER;

  const topic = PRODUCT_TOPICS.find((t) => t.match.test(lastUserMessage));
  if (!topic) return null;

  return {
    status: "ok",
    summary: topic.summary,
    warnings: [],
    suggestions: [...topic.suggestions],
    flags: [],
    legalDisclaimer: AI_LEGAL_DISCLAIMER,
  };
}

/**
 * The topics this build can answer with no provider at all.
 *
 * The availability endpoint reports this so the panel can say what still works
 * while AI is off, instead of presenting itself as uniformly dead.
 */
export function listGroundedTopicIds(): readonly string[] {
  return ["pricing", ...PRODUCT_TOPICS.map((t) => t.id)];
}
