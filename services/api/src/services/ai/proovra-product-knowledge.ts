/* ===========================================================================
   DETERMINISTIC PRODUCT ANSWERS
   ===========================================================================

   WHY THIS EXISTS

   Every question in the assistant's own advertised competence — "how do I
   capture evidence", "what is a verification package", "what does TSA failed
   mean" — used to require a live provider call. `answerProductKnowledge` only
   recognised pricing, so everything else fell through to OpenAI. That made the
   assistant's usefulness conditional on an outbound API being reachable,
   enabled, funded and in budget, for questions whose answers are FIXED
   PROPERTIES OF THIS PRODUCT and cannot vary by request.

   The consequence was not merely a slow path. With platform AI disabled the
   policy gate returns 403 before the provider is ever consulted, so the
   assistant could not answer "how do I capture evidence" at all — a question
   it is grounded to answer from facts compiled into this very file.

   WHY IT IS A ROUTER, NOT A SECOND KNOWLEDGE BASE

   The facts already live in `PROOVRA_PRODUCT_FACTS`, which is also what
   `buildProductKnowledgePromptSection` feeds to the model. If these answers
   restated them in their own prose there would be two descriptions of custody
   to keep in step, and the one that drifts is always the one nobody reads.

   So a topic owns only two things: how to RECOGNISE the question, and which
   facts ANSWER it. The prose is the facts. When a fact changes, every surface
   that quotes it changes with it, and `PRODUCT_KNOWLEDGE_VERSION` is the one
   thing to bump.

   WHAT THIS IS NOT

   It is not an intent classifier, and it does not try to be exhaustive. It
   answers what it can prove from the bundle and returns null otherwise, which
   sends the question down the provider path exactly as before. A topic that
   matched but had nothing grounded to say would be worse than no topic.
=========================================================================== */

