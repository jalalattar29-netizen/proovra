/**
 * Pricing is deliberately NOT a row in the table above.
 *
 * Every other topic answers with a fact. Pricing answers by REFUSING to state
 * a number — prices vary by currency, cycle and add-ons, so the only honest
 * answer is the Billing page. Keeping it separate keeps that asymmetry visible
 * rather than hiding a non-answer among answers.
 */
function isPricingQuestion(text: string): boolean {
  return /\b(price|pricing|cost|premium|primum|pro plan|subscription|billing|how much|اشتراك|سعر|تكلفة|بريميوم|برو)\b/i.test(
    text
  );
}

